def get_language():
    code = os.environ.get("DAVI_LANGUAGE", "en").lower().strip()
    return code if code in LANGUAGES else "en"


def get_voice_gender():
    gender = os.environ.get("DAVI_VOICE_GENDER", "female").lower().strip()
    return gender if gender in ("female", "male") else "female"


def tts_voices_for(gender=None):
    gender = gender or get_voice_gender()
    return TTS_VOICES_MALE if gender == "male" else TTS_VOICES_FEMALE


def current_tts_voice(lang=None, gender=None):
    voices = tts_voices_for(gender)
    code = lang or get_language()
    if code not in LANGUAGES:
        code = "en"
    return voices.get(code, voices["en"])


def set_voice_gender(gender):
    gender = (gender or "female").lower().strip()
    if gender not in ("female", "male"):
        gender = "female"
    os.environ["DAVI_VOICE_GENDER"] = gender
    try:
        import config
        config.VOICE_GENDER = gender
        config.save_env(DAVI_VOICE_GENDER=gender)
    except Exception:
        pass
    try:
        from services.tts import set_voice
        set_voice(current_tts_voice(gender=gender))
    except Exception:
        pass
    return gender


def set_language(code):
    code = (code or "en").lower().strip()
    if code not in LANGUAGES:
        code = "en"
    os.environ["DAVI_LANGUAGE"] = code
    try:
        import config
        config.LANGUAGE = code
        config.save_env(DAVI_LANGUAGE=code)
    except Exception:
        pass
    try:
        from services.tts import set_voice
        set_voice(current_tts_voice(lang=code))
    except Exception:
        pass
    return code


def t(key):
    lang = get_language()
    table = _STRINGS.get(lang) or _STRINGS["en"]
    return table.get(key) or _STRINGS["en"].get(key, key)


def greeting(name=""):
    name = (name or "").strip()
    if name:
        return f"{t('greet_named').format(name=name)} {t('help')}".strip()
    return f"{t('greet_hi')} {t('help')}".strip()


def language_prompt():
    lang = get_language()
    name = LANGUAGE_NAMES.get(lang, "English")
    return (
        f"ALWAYS respond in {name}. Spoken [Response] text and answer command text "
        f"must be {name}. JSON command names stay in English. Understand the user "
        f"in any language, then reply in {name}."
    )


def whisper_language():
    return get_language()


def apply_runtime_language(code, voice_processor=None):
    code = set_language(code)
    if voice_processor is not None:
        try:
            voice_processor.language = whisper_language()
            voice_processor.whisper_prompt = t("whisper_prompt")
        except Exception:
            pass
    return code
